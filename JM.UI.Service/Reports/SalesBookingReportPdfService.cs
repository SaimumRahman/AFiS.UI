using JM.UI.Entities.Model.Reporting_D;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using System;
using System.Collections.Generic;
using System.Linq;

namespace JM.UI.Service.Reports;

public class SalesBookingReportPdfService
{
    private const float BodyFont = 7f;
    private const float HeadFont = 7f;

    public byte[] GenerateSalesBookingReport(
        SalesBookingReportDTO report,
        string storeName = "-",
        DateTime? dateFrom = null,
        DateTime? dateTo = null,
        string printedBy = "-")
        => BuildDocument(report, storeName, dateFrom, dateTo, printedBy).GeneratePdf();

    public Document BuildDocument(
        SalesBookingReportDTO report,
        string storeName = "-",
        DateTime? dateFrom = null,
        DateTime? dateTo = null,
        string printedBy = "-")
    {
        QuestPDF.Settings.License = LicenseType.Community;

        var invoices = report?.Invoices ?? new List<SalesBookingInvoiceDTO>();
        var bookings = report?.Bookings ?? new List<SalesBookingBookingDTO>();

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4.Landscape());
                page.Margin(16);
                page.DefaultTextStyle(x => x.FontSize(BodyFont).FontFamily("Arial"));

                page.Header().Element(h => ComposeHeader(h, storeName, dateFrom, dateTo, printedBy));
                page.Content().Element(c => ComposeContent(c, invoices, bookings));
                page.Footer().Element(ComposeFooter);
            });
        });
    }

    private void ComposeHeader(IContainer container, string storeName, DateTime? dateFrom, DateTime? dateTo, string printedBy)
    {
        var range = (dateFrom.HasValue && dateTo.HasValue)
            ? $"{dateFrom:dd-MMM-yyyy}  TO  {dateTo:dd-MMM-yyyy}"
            : "ALL TIME";
        var printed = DateTime.Now.ToString("dd-MMM-yyyy HH:mm");

        container.Column(col =>
        {
            col.Item().AlignCenter().Text("ASIA FASHION").Bold().FontSize(12);
            col.Item().AlignCenter()
                .Text("HOSSAIN PLAZA (1ST FLOOR), BANDARTILA, CHATTOGRAM.").FontSize(8.5f);
            col.Item().AlignCenter().Text("SALES & BOOKING REPORT").Bold().FontSize(10);
            col.Item().AlignCenter()
                .Text($"Branch: {storeName}   |   {range}   |   Generated By: {printedBy}")
                .FontSize(8);
            col.Item().AlignRight().Text($"Print Date: {printed}").FontSize(7.5f).FontColor("#555555");
            col.Item().PaddingBottom(4).LineHorizontal(0.8f).LineColor("#999999");
        });
    }

    private void ComposeContent(IContainer container, List<SalesBookingInvoiceDTO> invoices, List<SalesBookingBookingDTO> bookings)
    {
        container.Column(col =>
        {
            col.Spacing(8);

            // ── 1. Sales & Exchanges ──
            col.Item().Text("1. Sales & Exchanges").Bold().FontSize(9);

            if (!invoices.Any())
            {
                col.Item().Text("No sales found for the selected filters.").Italic().FontColor("#777777");
            }
            else
            {
                col.Item().Table(table =>
                {
                    table.ColumnsDefinition(c =>
                    {
                        c.RelativeColumn(1.5f); // Invoice
                        c.RelativeColumn(1.7f); // Customer
                        c.RelativeColumn(3.6f); // Items
                        c.RelativeColumn(0.9f); // Bill
                        c.RelativeColumn(0.8f); // Camp disc
                        c.RelativeColumn(0.8f); // Inv disc
                        c.RelativeColumn(0.9f); // Net
                        c.RelativeColumn(0.8f); // Exc
                        c.RelativeColumn(1.5f); // Paid
                        c.RelativeColumn(0.7f); // Due
                    });

                    table.Header(header =>
                    {
                        foreach (var title in new[]
                                 { "Invoice No", "Customer", "Item Details & Salesman", "Bill Amt", "Camp Disc",
                                   "Inv Disc", "Net Amt", "Exc Amt", "Paid & Breakdown", "Due" })
                        {
                            header.Cell().Background("#ECEFF3").Padding(2).Text(title).Bold().FontSize(HeadFont);
                        }
                    });

                    foreach (var inv in invoices)
                    {
                        table.Cell().Padding(2).Column(c =>
                        {
                            c.Item().Text(inv.InvoiceNo).Bold().FontSize(BodyFont).FontColor("#1d4ed8");
                            c.Item().Text(inv.CreatedDate.ToString("dd MMM yyyy")).FontSize(6.5f).FontColor("#666666");
                            c.Item().Text(inv.CreatedDate.ToString("HH:mm")).FontSize(6.5f).FontColor("#666666");
                            if (!string.IsNullOrWhiteSpace(inv.ReturnInvoiceNo))
                                c.Item().Text($"Ref: {inv.ReturnInvoiceNo}").FontSize(6.5f).FontColor("#666666");
                        });

                        table.Cell().Padding(2).Column(c =>
                        {
                            c.Item().Text(CustomerLabel(inv.CustomerId, inv.CustomerName)).Bold();
                            c.Item().Text($"Served By: {inv.ServedByName}").FontSize(6.5f).FontColor("#666666");
                        });

                        table.Cell().Padding(2).Column(c =>
                        {
                            foreach (var line in inv.Lines)
                            {
                                var text = $"{line.Barcode} {line.ProductName} [{line.Qty:N0}] x {line.UnitPrice:N2}";
                                if (!string.IsNullOrWhiteSpace(line.SalesPersonName))
                                    text += $"  (Sales: {line.SalesPersonName})";
                                c.Item().Text(text).FontSize(BodyFont);
                                if (line.IsReturn)
                                    c.Item().Text($"(Return/Exchange) prev ref: {line.ReturnRefNo}")
                                        .FontSize(6.5f).FontColor("#dc2626");
                            }
                        });

                        table.Cell().Padding(2).AlignRight().Text(inv.TotalBill.ToString("N0"));
                        table.Cell().Padding(2).AlignRight().Text(inv.CampaignDiscount.ToString("N0")).FontColor("#dc2626");
                        table.Cell().Padding(2).AlignRight().Text(inv.InvoiceDiscount.ToString("N0")).FontColor("#dc2626");
                        table.Cell().Padding(2).AlignRight().Text(inv.NetAmount.ToString("N0")).Bold();

                        table.Cell().Padding(2).AlignRight()
                            .Text(inv.ExchangeAmount != 0 ? "- " + Math.Abs(inv.ExchangeAmount).ToString("N0") : "0")
                            .FontColor(inv.ExchangeAmount != 0 ? "#dc2626" : "#000000");

                        table.Cell().Padding(2).Column(c =>
                        {
                            c.Item().AlignRight().Text(inv.TotalPaid.ToString("N0")).Bold();
                            foreach (var pay in inv.Payments)
                                c.Item().AlignRight()
                                    .Text($"{pay.PaymentMethod}: {pay.Amount:N0}").FontSize(6.5f).FontColor("#555555");
                        });

                        table.Cell().Padding(2).AlignRight().Text(inv.TotalDue.ToString("N0"));
                    }

                    // Totals row
                    table.Cell().ColumnSpan(3).Background("#F1F5F9").Padding(2).AlignRight().Text("MAIN GRID TOTALS:").Bold();
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(invoices.Sum(i => i.TotalBill).ToString("N0")).Bold();
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(invoices.Sum(i => i.CampaignDiscount).ToString("N0")).Bold().FontColor("#dc2626");
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(invoices.Sum(i => i.InvoiceDiscount).ToString("N0")).Bold().FontColor("#dc2626");
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(invoices.Sum(i => i.NetAmount).ToString("N0")).Bold();
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(SignedTotal(invoices.Sum(i => i.ExchangeAmount))).Bold();
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(invoices.Sum(i => i.TotalPaid).ToString("N0")).Bold();
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(invoices.Sum(i => i.TotalDue).ToString("N0")).Bold();
                });
            }

            // ── 2. New Bookings ──
            col.Item().PaddingTop(4).Text("2. New Bookings").Bold().FontSize(9);

            if (!bookings.Any())
            {
                col.Item().Text("No new bookings for the selected filters.").Italic().FontColor("#777777");
            }
            else
            {
                col.Item().Table(table =>
                {
                    table.ColumnsDefinition(c =>
                    {
                        c.RelativeColumn(1.5f); // Booking no
                        c.RelativeColumn(1.7f); // Customer
                        c.RelativeColumn(3.6f); // Items
                        c.RelativeColumn(1f);   // Total
                        c.RelativeColumn(1.5f); // Advance
                        c.RelativeColumn(1f);   // Due
                    });

                    table.Header(header =>
                    {
                        foreach (var title in new[]
                                 { "Booking No.", "Customer", "Booked Items & Salesman", "Total Value", "Advance Paid", "Due Balance" })
                        {
                            header.Cell().Background("#ECEFF3").Padding(2).Text(title).Bold().FontSize(HeadFont);
                        }
                    });

                    foreach (var bk in bookings)
                    {
                        table.Cell().Padding(2).Column(c =>
                        {
                            c.Item().Text(bk.BookingNo).Bold().FontColor("#0f766e");
                            c.Item().Text(bk.CreatedDate.ToString("dd MMM yyyy")).FontSize(6.5f).FontColor("#666666");
                            c.Item().Text(bk.CreatedDate.ToString("HH:mm")).FontSize(6.5f).FontColor("#666666");
                        });

                        table.Cell().Padding(2).Column(c =>
                        {
                            c.Item().Text(CustomerLabel(bk.CustomerId, bk.CustomerName)).Bold();
                            c.Item().Text($"Served By: {bk.ServedByName}").FontSize(6.5f).FontColor("#666666");
                        });

                        table.Cell().Padding(2).Column(c =>
                        {
                            foreach (var line in bk.Lines)
                            {
                                var text = $"{line.Barcode} {line.ProductName} [{line.Qty:N0}] x {line.UnitPrice:N2}";
                                if (!string.IsNullOrWhiteSpace(line.SalesPersonName))
                                    text += $"  (Sales: {line.SalesPersonName})";
                                c.Item().Text(text).FontSize(BodyFont);
                            }
                        });

                        table.Cell().Padding(2).AlignRight().Text(bk.TotalBill.ToString("N0"));

                        table.Cell().Padding(2).Column(c =>
                        {
                            c.Item().AlignRight().Text(bk.AdvancePaid.ToString("N0")).Bold().FontColor("#15803d");
                            foreach (var pay in bk.Payments)
                                c.Item().AlignRight()
                                    .Text($"{pay.PaymentMethod}: {pay.Amount:N0}").FontSize(6.5f).FontColor("#555555");
                        });

                        table.Cell().Padding(2).AlignRight().Text(bk.DueBalance.ToString("N0")).Bold().FontColor("#dc2626");
                    }

                    table.Cell().ColumnSpan(3).Background("#F1F5F9").Padding(2).AlignRight().Text("BOOKING TOTALS:").Bold();
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(bookings.Sum(b => b.TotalBill).ToString("N0")).Bold();
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(bookings.Sum(b => b.AdvancePaid).ToString("N0")).Bold().FontColor("#15803d");
                    table.Cell().Background("#F1F5F9").Padding(2).AlignRight().Text(bookings.Sum(b => b.DueBalance).ToString("N0")).Bold().FontColor("#dc2626");
                });
            }

            // ── 3. Collection Summary ──
            var payments = invoices.SelectMany(i => i.Payments)
                                   .Concat(bookings.SelectMany(b => b.Payments))
                                   .ToList();
            var cash = payments.Where(p => p.PaymentType == "Cash").Sum(p => p.Amount);
            var mfs = payments.Where(p => p.PaymentType == "MFS").Sum(p => p.Amount);
            var bank = payments.Where(p => p.PaymentType == "Bank").Sum(p => p.Amount);

            col.Item().PaddingTop(4).Text("Collection Summary").Bold().FontSize(9);

            col.Item().Table(table =>
            {
                table.ColumnsDefinition(c =>
                {
                    c.RelativeColumn(3);
                    c.RelativeColumn(1);
                });

                void Row(string label, decimal value, bool bold = false, string? color = null)
                {
                    table.Cell().Padding(2).Text(label).FontSize(8);
                    var cell = table.Cell().Padding(2).AlignRight().Text(value.ToString("N0")).FontSize(8);
                    if (bold) cell.Bold();
                    if (color != null) cell.FontColor(color);
                }

                Row("Total Cash (Drawer)", cash);
                Row("Total MFS (bKash, Nagad)", mfs);
                Row("Total Cards (Bank POS)", bank);
                Row("TOTAL PHYSICAL COLLECTION", cash + mfs + bank, bold: true, color: "#047857");
                Row("Total Invoices Created", invoices.Count);
                Row("Gross Sales (Items Sold)", invoices.Sum(i => i.TotalBill));
            });
        });
    }

    private void ComposeFooter(IContainer container)
    {
        container.Row(row =>
        {
            row.RelativeItem().Text("AFiS ERP — Sales & Booking Report").FontSize(7).FontColor("#777777");
            row.RelativeItem().AlignRight().Text(x =>
            {
                x.Span("Page ").FontSize(7).FontColor("#777777");
                x.CurrentPageNumber().FontSize(7).FontColor("#777777");
                x.Span(" / ").FontSize(7).FontColor("#777777");
                x.TotalPages().FontSize(7).FontColor("#777777");
            });
        });
    }

    private static string CustomerLabel(int? customerId, string? name)
    {
        var trimmed = (name ?? string.Empty).Trim();
        if (string.IsNullOrWhiteSpace(trimmed))
            return customerId is > 0 ? $"C-{customerId:D4}" : "Walk-in";
        return customerId is > 0 ? $"{trimmed} (C-{customerId:D4})" : trimmed;
    }

    private static string SignedTotal(decimal value)
        => value != 0 ? "- " + Math.Abs(value).ToString("N0") : "0";
}
